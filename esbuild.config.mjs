/**
 * esbuild 构建配置（Obsidian 插件标准形态）。
 *
 *   node esbuild.config.mjs              → watch 模式（开发）
 *   node esbuild.config.mjs production   → 单次构建（发版）
 *
 * 产物：main.js（CJS，供 Obsidian 加载；obsidian / electron / node 内置模块保持外部依赖）。
 */

import esbuild from "esbuild";
import process from "node:process";
import { builtinModules } from "node:module";

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
源码见 main.ts 与 src/；请勿直接修改本文件。
*/`;

const prod = process.argv[2] === "production";

const external = [
  "obsidian",
  "electron",
  "@codemirror/*",
  "@lezer/*",
  ...builtinModules,
  ...builtinModules.map((name) => `node:${name}`),
];

const context = await esbuild.context({
  banner: { js: banner },
  entryPoints: ["main.ts"],
  bundle: true,
  external,
  format: "cjs",
  target: "es2022",
  platform: "browser",
  charset: "utf8",
  logLevel: "info",
  sourcemap: prod ? false : "inline",
  treeShaking: true,
  minify: prod,
  outfile: "main.js",
});

if (prod) {
  await context.rebuild();
  await context.dispose();
  process.exit(0);
} else {
  await context.watch();
}
